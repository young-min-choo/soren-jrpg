#!/usr/bin/env python3
"""Export reviewed npc walk sheets into the game + regenerate the sheet manifest.

Copies design-spike/npc_sheets/<name>/sheet_48x96.png -> public/sprites/npc_sheets/<name>.png
and writes src/game/npc-sheet-manifest.json (keys only). BootScene loads
spritesheets ONLY for keys in this manifest, so a sheet missing on disk can
never 404 — the static npc_<key>.png fallback stays.

Usage: python3 soren_wire_export.py [--all | name ...]
"""
import json
import os
import shutil
import sys

REPO = "/home/min/dev/soren-jrpg"
SHEETS = os.path.join(REPO, "design-spike", "npc_sheets")
PUB_OUT = os.path.join(REPO, "public", "sprites", "npc_sheets")
MANIFEST = os.path.join(REPO, "src", "game", "npc-sheet-manifest.json")


def main():
    args = sys.argv[1:]
    names = [a for a in args if not a.startswith("--")]
    if "--all" in args or not names:
        names = sorted(d for d in os.listdir(SHEETS) if os.path.isdir(os.path.join(SHEETS, d)))
    os.makedirs(PUB_OUT, exist_ok=True)
    exported = []
    for n in names:
        src = os.path.join(SHEETS, n, "sheet_48x96.png")
        if not os.path.exists(src):
            print(f"[skip] {n}: no sheet")
            continue
        shutil.copy(src, os.path.join(PUB_OUT, f"{n}.png"))
        exported.append(n)
    json.dump({
        "_comment": "Generated by design-spike/bin/soren_wire_export.py — NPC 12-frame walk sheet keys (48x96, 16x24 frames). BootScene loads spritesheets only for these keys; missing keys fall back to static npc_<key>.png.",
        "npc_sheets": exported,
    }, open(MANIFEST, "w"), indent=2)
    print(f"exported {len(exported)} sheets -> {PUB_OUT}")
    print(f"manifest -> {MANIFEST} ({len(exported)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())